/**
 * @file svc_lvgl.h
 * @brief 服务层：把 LVGL 的显示服务绑定到 ST7789 设备
 * @author Ricardo
 * @date 2026-11-07
 *
 * @note 第三方库的适配器要放在"需要它的层"，不能塞进 Device：
 *       Device 只回答"这块屏能做什么"（开窗、写像素），不该知道世界上
 *       有没有 LVGL。本服务负责的是跨设备组合——LVGL 内核 ↔ dev_st7789_0，
 *       这正是 Service 的职责。
 *
 *       头文件不出现 lv_ 类型，也不出现 dev_st7789_t：display 指针、渲染
 *       缓冲与面板句柄都留在 .c 里，上层只能调 Init / Step，因此依赖全部
 *       写成 PRIVATE，别人的类型不会顺着头文件传给 APP / TASK。
 *
 *       毫秒时基由本模块内部提供（直接取 OS 的 tick 计数）：本层已经因
 *       切屏信号量依赖 cmsis_os2.h，把时基放进来不新增依赖类型，也让
 *       调用方少一个必须传对的参数。代价是"换 OS 只改 TASK"对本服务
 *       不再成立——换 OS 时 .c 里的 osKernelGetTickCount() 要跟着换，
 *       但头文件与调用方完全不受影响。
 *
 *       本服务同时是"请求显示线程做一次界面动作"的唯一入口
 *       （Svc_LVGL_Request_Switch）：谁想切屏就调它，不需要知道下面是
 *       二值信号量。信号量由 CubeMX 创建，本模块只 extern 句柄、不创建。
 *       当前切到第几屏仍由 APP_Screen 持有，本服务不记界面状态。
 */

#ifndef __Svc_LVGL_H__
#define __Svc_LVGL_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 初始化 LVGL 显示服务：面板 → 内核 → 时基 → display → 缓冲 → flush
 * @retval 0: 初始化成功
 * @retval -1: ST7789 面板初始化失败（SPI 时序、几何配置或调度器未运行）
 * @retval -2: lv_display_create() 返回 NULL（LVGL 堆不足）
 * @retval -3: 面板当前逻辑宽高与本服务的缓冲/显示常量不一致
 * @note 必须在**调度器启动之后的线程里**调用：Dev_ST7789_Init() 内部用
 *       osDelay 等复位时序，调度器没跑时延时会全部落空；毫秒时基也
 *       依赖内核已启动才能取到 tick 计数。
 *       本函数之后才能创建任何 LVGL 对象（APP_Screen_Init() 依赖它）。
 */
int Svc_LVGL_Init(void);

/**
 * @brief 推进 LVGL 的定时器与重绘队列
 * @retval 无
 * @note 必须在创建本端口的那一个线程里周期调用（建议 5~10 ms 一次）：
 *       LVGL 不是线程安全的，所有 LVGL 调用（含界面切换）都必须与
 *       本函数处于同一线程上下文。
 */
void Svc_LVGL_Step(void);

/**
 * @brief 请求显示线程尽快执行一次界面动作（当前用途：切到下一屏）
 * @retval 0: 请求已发出
 * @retval -1: 上一次请求还没被消费（二值语义：请求不排队）
 * @note 非阻塞，可在按键命令线程里直接调用，不会拖慢事件处理。
 *       本函数只负责"唤醒显示线程"，不决定切到哪一屏：界面索引由
 *       APP_Screen 持有，真正的 lv_screen_load() 在 Task_LVGL 里执行
 *       （LVGL 不是线程安全的，所有 LVGL 调用必须与 Step 同线程）。
 *       二值语义决定"请求不排队"：显示线程还没切完时再次按下，本次
 *       请求被丢弃，不会积压成"松开手后连切好几屏"。
 */
int Svc_LVGL_Request_Switch(void);

#endif /* __Svc_LVGL_H__ */
