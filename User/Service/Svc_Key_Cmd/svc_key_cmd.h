/**
 * @file svc_key_cmd.h
 * @brief 服务层：按键命令表分发（表由调用方作为参数传入）
 * @author Ricardo
 * @date 2026-11-09
 *
 * @note 本模块只回答"这条事件该调哪个函数"，既不拥有表，也不定义动作。
 *       表的实体在 APP 层（extern const 数组），每次分发整表传进来。
 *       于是本层对"档位""步数""界面"一无所知——换一张表就是换一套
 *       动作，本模块一行不用改。
 *
 *       表为什么必须是参数，不能放本模块的 static：
 *         表里的 handler 是 APP 的业务动作。表若落在服务层，服务就得
 *         include APP 的头文件，依赖方向立刻反过来（Service → APP），
 *         分层也就名存实亡。把表当参数传，本层只认
 *         { 键句柄, 事件, 函数指针 } 这三个字段，编译期看不见任何业务符号。
 *
 *       为什么暂时没有 Init / 注册接口：
 *         当前只有一个使用者，表是 APP 导出的 const 数组，生命周期覆盖
 *         整个运行期，运行期注册没有收益。将来若要支持多张表或由 APP
 *         主动注入回调，加一个 Svc_Key_Cmd_Register_Callback() 即可，
 *         分发函数的签名不用动——它本来就是"给表、分发"的形态。
 *
 *       本层不碰 OS：没有任何内核调用，也不知道自己被哪个线程调；
 *       handler 的执行上下文就是调用者的上下文。
 */

#ifndef __Svc_Key_Cmd_H__
#define __Svc_Key_Cmd_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
// 功能包含
#include "svc_key_logic.h"      /* key_event_t / dev_key_t：表项的两个匹配键 */

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 命令表条目：哪个键的哪个事件调哪个处理函数
 * @note 完整定义在头文件是刻意的：表是配置数据，调用方要按值定义数组、
 *       要用 sizeof 算行数，符合"小型稳定值类型可完整暴露"的例外。
 */
typedef struct {
    const dev_key_t *key;       /* 按键设备句柄，按对象地址匹配 */
    key_event_t      event;     /* 触发事件 */
    void           (*handler)(void); /* 命中后执行的动作，可为 NULL（视为未绑定） */
} svc_key_cmd_entry_t;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 按键命令分发：在给定命令表中查 { key, event } 并执行对应 handler
 * @param table 命令表首地址，不可为 NULL
 * @param count 表行数，必须与 table 的实际长度一致（本函数不做越界校验）
 * @param key   按键设备句柄，按对象地址比较；不可为 NULL
 * @param event 按键事件（KEY_EVENT_*）
 * @retval 1: 命中且已执行 handler
 * @retval 0: 未命中或参数非法，未执行任何 handler
 * @note handler 在调用者线程里同步执行，因此必须是无参短动作：
 *       不阻塞、不睡眠，否则会拖慢调用者的处理节拍。
 *       线性查表，命中第一条即返回；表里出现重复行时后面的行不会被执行。
 */
uint8_t Svc_Key_Cmd_Dispatch(const svc_key_cmd_entry_t *table, uint8_t count,
                             const dev_key_t *key, key_event_t event);

#endif /* __Svc_Key_Cmd_H__ */
