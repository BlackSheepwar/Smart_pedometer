/**
 * @file app_screen.c
 * @brief 应用层：界面生命周期与数据同步实现
 * @author Ricardo
 * @date 2026-11-09
 *
 * @note 本文件只有两个函数共十几行，看起来"薄"，但它承担的是
 *       界面语义的所有权：谁建屏、什么时候刷、刷什么值。
 *       把这些散到 Task_LVGL 里会让线程体同时知道 UI 和业务；
 *       散到 app_ui_port 里又会让"适配层"变成"业务层"。
 *
 *       上一版这里有一整套手写的两屏构造代码（APP_Screen_Make、
 *       两条顶条、四段文案、两套配色宏），全部随界面改用 LVGL Pro
 *       导出代码而删除。界面形态从此只在 Editor 的 XML 里定义，
 *       C 侧不再重复描述颜色和坐标。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include "app_screen.h"
// 功能包含
#include "app_step.h"            /* 业务数据来源 */
#include "app_ui_port.h"         /* 界面适配层：Init 与 Set_Steps */

/*==============================================================================
 * 接口实现
 *============================================================================*/
/**
 * @brief 建立界面并显示首帧
 * @retval 无
 * @note 先 Init 再补一次 Step：导出代码里 subject_steps 的初值是
 *       globals.xml 里的演示值 8432，不立刻覆盖的话上电会先闪一下 8432。
 */
void APP_Screen_Init(void)
{
    App_UI_Init();
    APP_Screen_Step();
}

/**
 * @brief 把一个显示节拍的数据同步到界面
 * @retval 无
 * @note 去重放在 App_UI_Set_Steps() 里（它记得上次写入的值），
 *       本函数不重复持有第二份缓存——两份缓存迟早会不同步。
 */
void APP_Screen_Step(void)
{
    App_UI_Set_Steps(APP_Step_Total());
}
