/**
 * @file app_step.c
 * @brief 应用层：步数计数的业务状态实现
 * @author Ricardo
 * @date 2026-11-09
 *
 * @note 本文件只有三个函数和一个整数，不加锁的理由见头文件的线程模型段。
 *       这里再说明一次"为什么 volatile 而不是原子操作"：
 *         写入者是单线程，且对 s_total 只做一次完整的 32 位 STR；
 *         读取者是另一个单线程，只做一次 32 位 LDR。
 *       Cortex-M4 对齐的 32 位读写不可分割，读到的必然是某次写之前的
 *       完整值或之后的完整值，不会出现"半个数"。
 *       volatile 在这里的作用是阻止编译器把 s_total 提到寄存器里缓存
 *       （否则显示线程可能永远读到循环外的旧值），不承担内存序职责——
 *       单核单写者的场景也不需要内存序。
 *       若将来出现第二个写入者（例如定时器中断里也累加），必须改成
 *       临界区或 __LDREX/__STREX，否则"读-改-写"三步之间会被打断。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
#include "app_step.h"

/*==============================================================================
 * 静态变量
 *============================================================================*/
/**
 * @brief 当前累计步数
 * @note 单写者：只有 APP_Step_Add() 写它，且只从 Task_Key_Cmd 调用。
 */
static volatile int32_t s_total = 0;

/*==============================================================================
 * 接口实现
 *============================================================================*/
/**
 * @brief 计数归零
 * @retval 无
 */
void APP_Step_Init(void)
{
    s_total = 0;
}

/**
 * @brief 增加步数（自动夹取到 [0, APP_STEP_MAX]）
 * @param delta 增量
 * @retval 无
 * @note 先算后写：中间量放在局部变量里，保证 s_total 只被写一次，
 *       读者不会看到"已加但未夹取"的值。
 */
void APP_Step_Add(int32_t delta)
{
    int32_t next = s_total + delta;

    if (next < 0) {
        next = 0;
    } else if (next > APP_STEP_MAX) {
        next = APP_STEP_MAX;
    }

    s_total = next;
}

/**
 * @brief 读当前步数
 * @retval 当前累计步数
 */
int32_t APP_Step_Total(void)
{
    return s_total;
}
