/**
 * @file app_step.h
 * @brief 应用层：步数计数的业务状态
 * @author Ricardo
 * @date 2026-11-09
 *
 * @note 为什么单独一个模块，而不是塞进 APP_Screen：
 *         - APP_Screen 是界面层，计数是业务状态，且按键侧要改计数，
 *           若计数放界面层，app_key_cmd 就得依赖 app_screen，
 *           而 app_screen 又会依赖 app_ui —— 一条本不该存在的边。
 *       现在是 app_key_cmd → app_step ← app_screen，两边都只依赖业务状态。
 *
 *       线程模型（本模块存在的核心理由）：
 *         写入者：只有 Task_Key_Cmd 一个线程（经 app_key_cmd 的命令表）；
 *         读取者：只有 Task_LVGL 一个线程（每 10 ms 同步一次到界面）。
 *       单写者 + 单读者 + 32 位对齐量，读写各自是一条 STR/LDR，
 *       Cortex-M4 上天然原子，因此本模块**不加任何锁**，
 *       也就不需要 include 任何 OS 头文件，APP 层"不碰内核"的约定仍成立。
 *       代价：读者可能读到上一次写入前的值，最多滞后一个显示节拍（10 ms），
 *       下一拍自动纠正。计数场景下这个滞无误不可见。
 *
 *       本模块不引用任何 lv_ 类型，也不 include lvgl.h：它只存一个整数，
 *       什么时候送到界面上是 APP_Screen 的事。
 */

#ifndef __APP_STEP_H__
#define __APP_STEP_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/**
 * @brief 计数上限
 * @note 与三块界面的量程一致（APP_UI_STEPS_MAX 也是 100）。超过上限后
 *       计数不再增长，避免界面上的数字与圆弧出现"值被 UI 夹住、内部还在涨"
 *       的错位——圆弧与进度条的 max 也正好是 100，100 即满环。
 *       改这里时三处要一起改：本宏、APP_UI_STEPS_MAX、
 *       UI_Export/screens/screen2_gen.c 里进度条的 max 与 "/ 100" 文案。
 */
#define APP_STEP_MAX            100

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 计数归零
 * @retval 无
 * @note 由 Src/freertos.c 的 MX_FREERTOS_Init() 在调度器启动前调用，
 *       语义是"上电从 0 步开始"。
 *       静态量本来就是 0，显式调用是为了让"上电初值"由代码表达，
 *       而不是依赖 .bss 清零。
 *       放启动前的理由：它是全局业务状态，不该由消费它的线程来初始化——
 *       Task_LVGL 每 10 ms 就会读它，若由 Task_Key_Cmd 初始化，第一次
 *       读到时是否已初始取决于两个线程的调度顺序。
 */
void APP_Step_Init(void);

/**
 * @brief 增加步数
 * @param delta 增量，正数累加、负数递减
 * @retval 无
 * @note **只能由 Task_Key_Cmd 线程调用**（单写者约定，见文件头）。
 *       结果自动夹在 [0, APP_STEP_MAX]。B10 传 +1、B11 传 -1。
 *       本函数不含任何阻塞或 LVGL 调用，可以在命令表的 handler 里直接调，
 *       不会拖慢 8 格深的事件队列。
 */
void APP_Step_Add(int32_t delta);

/**
 * @brief 读当前步数
 * @retval 当前累计步数，范围 [0, APP_STEP_MAX]
 * @note **只能由 Task_LVGL 线程调用**（单读者约定，见文件头）。
 *       无副作用，不清零，不占用任何状态：显示线程每次拿到的都是
 *       一个完整的快照，用"与上次显示值比较"来决定要不要刷新界面。
 */
int32_t APP_Step_Total(void);

#endif /* __APP_STEP_H__ */
