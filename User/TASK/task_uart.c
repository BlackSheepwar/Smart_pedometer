/**
 * @file task_uart.c
 * @brief 任务层：UART 服务线程体（等事件 → 搬运 → 推进发送）
 * @author Ricardo
 * @date 2026-11-23
 *
 * @note 分工：
 *        - BSP_UART 只做循环 DMA 的窗口计数与事件上报，不复制字节；
 *        - Dev_UART 持有 2N DMA 缓冲与两个 FIFO，搬运和重装在服务函数里；
 *        - 本文件只回答"多久跑一次、按什么顺序跑"，不解析任何协议。
 *
 *       为什么是超时唤醒而不是纯事件驱动：
 *       中断只置发布位置并发任务通知，正常数据到达会立刻唤醒；
 *       超时唤醒用来兜底：发送完成、错误重装、溢出计数这类没有数据
 *       事件的路径，也靠它被服务函数检查一遍。
 *
 *       OS 依赖暂时内联在 Dev_UART：本文件只调用 Dev_UART_RegisterTask()
 *       把当前任务登记为服务任务，等 OSAL 解耦层重建后此处不变。
 *
 *       线程由 CubeMX 按 .ioc 的 UART_T 创建（优先级 24、栈 256），这里提供
 *       同名强定义，覆盖 Src/freertos.c 里生成的 __weak 空入口。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stddef.h>
// 功能包含
#include "dev_uart.h"

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/** @brief 服务任务单次等待的上限（ms），同时是兜底轮询周期 */
#define TASK_UART_WAIT_MS           10U

/*==============================================================================
 * 接口实现
 *============================================================================*/
/**
 * @brief UART 服务线程体：登记服务任务后循环等待并服务收发
 * @param argument RTOS 任务参数，未使用
 * @retval 无
 *
 * @note 先登记再进循环：Dev_UART_SignalIsr() 依赖这个任务句柄，顺序反了
 *       会丢最早的一批通知，表现为上电后第一帧迟到。
 *       服务函数内部按 RX 搬运 → 错误重装 → TX 推进 的顺序执行。
 */
void Task_UART(void *argument)
{
    (void)argument;

    /* ---------- 1. 把当前任务登记为 UART 服务任务 ---------- */
    Dev_UART_RegisterTask();

    /* ---------- 2. 等事件或超时，然后搬运接收并推进发送 ---------- */
    for (;;) {
        (void)Dev_UART_Wait(&dev_uart1, TASK_UART_WAIT_MS);
        (void)Dev_UART_Service(&dev_uart1);
    }
}
