/**
 * @file task_uart.c
 * @brief 任务层：UART 服务线程体（等指针 → 服务那一路）
 * @author Ricardo
 * @date 2026-11-23
 *
 * @note 事件队列给出哪个句柄，就服务哪一路；本文件不认识任何具体串口，
 *       新增 UART 只改设备层的实例登记与初始化。串口闲着就睡着，没有
 *       轮询、没有超时兜底。
 *
 *       线程由 CubeMX 按 .ioc 的 UART_T 创建（优先级 24、栈 256），这里提供
 *       同名强定义，覆盖 Src/freertos.c 里生成的 __weak 空入口。
 */

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stddef.h>
// 功能包含
#include "dev_uart.h"

/*==============================================================================
 * 接口实现
 *============================================================================*/
/**
 * @brief UART 服务线程体：按队列给出的指针服务对应串口
 * @param argument RTOS 任务参数，未使用
 * @retval 无
 *
 * @note 一条任务服务全部串口，不要再开第二条任务消费同一条队列。
 */
void Task_UART(void *argument)
{
    const dev_uart_t *dev = NULL;

    (void)argument;

    for (;;) {
        Dev_UART_Wait(&dev);
        (void)Dev_UART_Service(dev);
    }
}
