/**
 * @file dev_tsc2046.h
 * @brief 设备层：四线电阻触摸控制器（HR2046 / TSC2046 / XPT2046 / ADS7843 兼容）
 * @author Ricardo
 * @date 2026-11-15
 *
 * @note 只回答"这块触摸屏被按在哪里"，不回答"按下之后做什么"：
 *       采样、把原始码换成像素坐标在这里；判定点击、切界面由上层决定。
 *
 *       与屏幕的关系：触摸玻璃通常与 LCD 同尺寸，控制器输出的原始码覆盖整块
 *       玻璃，而 LCD 的可视区可能比它窄（只取玻璃中间一段）。所以本层除了
 *       做量程映射，还会减掉句柄里的 x_offset / y_offset，
 *       **直接返回 LCD 的逻辑坐标**。
 *       代价是这两份几何必须与 dev_st7789_0 保持一致——改屏宽时必须同时改
 *       dev_st7789.c 与本文件末尾的 dev_tsc2046_0，否则触摸点会整体偏移。
 *
 *       采样方式：一次事务固定 24 个 DCLK（1 字节命令 + 2 字节数据），
 *       读满 12 位。命令里的 PD1/PD0 必须为 00，否则 PENIRQ 会被关掉。
 *       DCLK 上限 2 MHz，由设备句柄的 sck_hz 保证（分频后不超过它）。
 *
 *       按下判定两种取法，由句柄的 irq 是否为空决定：
 *         接了 PENIRQ → 读引脚电平（低有效），最省事也最可靠；
 *         没接       → 采一次样，原始码落在有效量程内即认为按下。
 *       PENIRQ 在转换过程中会翻转，所以本层**不注册外部中断**，只把它当
 *       普通输入读取：调用方按自己的节奏轮询（例如 GUI 的 indev 回调）。
 *
 *       本层不建线程、不延时、不含任何 OS 头文件；传输超时交给 BSP。
 */

#ifndef __Dev_TSC2046_H__
#define __Dev_TSC2046_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 触摸控制器句柄（不透明类型，成员定义在 dev_tsc2046.c）
 */
typedef struct dev_tsc2046 dev_tsc2046_t;

/*==============================================================================
 * 外部声明
 *============================================================================*/
/**
 * @brief 默认触摸实例：映射到 240×320 可视区，PENIRQ 低有效
 * @note 原始量程 200~3900 只是这类模组的常见范围，用于让点击落在屏幕内；
 *       要精确到边角必须实测标定。
 */
extern const dev_tsc2046_t dev_tsc2046_0;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 校验句柄并标记就绪
 * @param tp 触摸句柄，不能为 NULL
 * @retval 0: 就绪，可以开始采样
 * @retval -1: 句柄或 SPI 设备句柄为空，或几何/量程参数自相矛盾
 * @note 必须在调度器启动之后调用：底层传输是"抢互斥量 + DMA + 任务通知"，
 *       调度器没跑会被 BSP 判成 ERR_STATE。
 *       本芯片没有 ID 寄存器，Init 无法验证器件是否真的在线；接错线或
 *       没上电的现象是"永远读不到按下"，只能靠现象反推。
 */
int Dev_TSC2046_Init(const dev_tsc2046_t *tp);

/**
 * @brief 查询当前是否被按下
 * @param tp 触摸句柄，不能为 NULL
 * @retval 1: 有按下
 * @retval 0: 未按下，或句柄为空、未初始化、irq 未接且采样失败
 * @note 接了 PENIRQ 时只读一个 GPIO，不占 SPI 总线；没接时等价于做一次
 *       量程判定（会占用总线）。本函数不做消抖，抖动由调用方或 LVGL 处理。
 */
uint8_t Dev_TSC2046_Is_Pressed(const dev_tsc2046_t *tp);

/**
 * @brief 读一次原始坐标（12 位，未标定）
 * @param tp 触摸句柄，不能为 NULL
 * @param x  输出：X 通道原始码，0~4095
 * @param y  输出：Y 通道原始码，0~4095
 * @retval 0: 读成功
 * @retval -1: 句柄为空或未初始化
 * @retval -2: SPI 传输失败（片选、总线或超时）
 * @note X、Y 是两次独立事务，中间会放一次总线锁：这段时间别的 SPI 设备
 *       可以插进来，但两次采样之间本就不要求原子性。
 */
int Dev_TSC2046_Read_Raw(const dev_tsc2046_t *tp, uint16_t *x, uint16_t *y);

/**
 * @brief 读一次像素坐标（已标定、已换算到 LCD 逻辑坐标）
 * @param tp 触摸句柄，不能为 NULL
 * @param x  输出：逻辑列坐标，0 ~ 可视宽-1
 * @param y  输出：逻辑行坐标，0 ~ 可视高-1
 * @retval 0: 读成功
 * @retval -1: 句柄或输出指针为空，或未初始化
 * @retval -2: SPI 传输失败
 * @note **不做按下判断**：手指离开时通道浮空，读出的码同样能换算成一个
 *       合法坐标。所以调用前必须先 Dev_TSC2046_Is_Pressed()，否则会把
 *       浮空值当成一次点击。
 *       越界值夹到边界而不是报错：按在可视区外的黑边上时，返回最近的可视
 *       像素比返回错误码更容易被上层处理。
 */
int Dev_TSC2046_Read_Pixel(const dev_tsc2046_t *tp, uint16_t *x, uint16_t *y);

#endif /* __Dev_TSC2046_H__ */
