/**
 * @file dev_key.h
 * @brief 设备层：一个按键 = 一个 BSP 引脚句柄 + 极性
 * @author Ricardo
 * @date 2026-10-23
 *
 * @note 只回答"这个按键现在按着没有"，不回答"按多久算长按"。
 *       消抖、长按、连发属于业务逻辑，放在 Service 层。
 */

#ifndef __Dev_Key_H__
#define __Dev_Key_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 类型定义
 *============================================================================*/
/**
 * @brief 按键设备句柄（不透明类型，成员定义在 dev_key.c）
 */
typedef struct dev_key dev_key_t;

/*==============================================================================
 * 外部声明
 *============================================================================*/
/**
 * @brief 界面键 B1（PB1，上拉输入，低电平按下）：切换界面
 * @note 板子丝印是 B1。早期叫"减键"（那时用于灯排档位 -1），
 *       灯排移除后改为切屏；名字随功能改，避免与实际动作脱节。
 */
extern const dev_key_t dev_key_screen;
/**
 * @brief 加键 B10（PB10，上拉输入，低电平按下）：计数 +1
 * @note 板子丝印是 B10。早期叫"颜色键"（那时用它循环刷 LCD 三原色）。
 */
extern const dev_key_t dev_key_plus;
/**
 * @brief 减键 B11（PB11，上拉输入，低电平按下）：计数 -1
 * @note 板子丝印是 B11。早期叫"加键"（灯排档位 +1），现已反转用途。
 */
extern const dev_key_t dev_key_minus;
/**
 * @brief 灯键（PC13，下拉输入，**高电平按下**）：切换 PB2 板载 LED
 * @note 这块板子把 LED 从 PC13 挪到了 PB2，PC13 因此空出来做按键；
 *       该按键是"按下给高电平"的接法，极性与其他三个键相反。
 */
extern const dev_key_t dev_key_led;

/*==============================================================================
 * 函数声明
 *============================================================================*/
/**
 * @brief 读取按键当前是否按下
 * @param key 按键设备句柄
 * @retval 1: 按下
 * @retval 0: 松开
 */
uint8_t Dev_Key_Read(const dev_key_t *key);

#endif /* __Dev_Key_H__ */
